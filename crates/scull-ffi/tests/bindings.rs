//! The committed C header and C# bindings are what cbindgen and csbindgen
//! generate from the exports now; `SCULL_BLESS=1` rewrites them
//! (`just bindings`). `abi-drift` compares the rendered text and fails with
//! a unified diff when a file is stale. The header stays on this crate's
//! cbindgen 0.29.4; abi-drift's optional cbindgen is 0.29.3.

// Helpers outside #[test] functions are still test code; a failure here should abort loudly.
#![allow(clippy::unwrap_used, clippy::panic)]

use std::path::{Path, PathBuf};

/// Every module with exports. csbindgen reads each file alone; cbindgen
/// follows `mod` items from the crate root by itself.
const SOURCES: [&str; 13] = [
    "src/lib.rs",
    "src/config.rs",
    "src/guard.rs",
    "src/term.rs",
    "src/spawn.rs",
    "src/event.rs",
    "src/frame.rs",
    "src/input.rs",
    "src/text.rs",
    "src/select.rs",
    "src/link.rs",
    "src/link_target.rs",
    "src/prompt.rs",
];

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn drift() -> abi_drift::Drift {
    abi_drift::Drift::new(crate_dir())
        .bless_from_env("SCULL_BLESS")
        .regenerate_with("SCULL_BLESS=1 cargo test -p scull-ffi --test bindings")
}

#[test]
fn the_committed_c_header_is_what_cbindgen_generates() {
    let config = cbindgen::Config::from_file(crate_dir().join("cbindgen.toml")).unwrap();
    let mut rendered = Vec::new();
    cbindgen::Builder::new()
        .with_config(config)
        .with_src(crate_dir().join("src/lib.rs"))
        .generate()
        .unwrap()
        .write(&mut rendered);
    drift()
        .check("include/scull.h", &String::from_utf8(rendered).unwrap())
        .unwrap();
}

#[test]
fn the_committed_csharp_bindings_are_what_csbindgen_generates() {
    let out = Path::new(env!("CARGO_TARGET_TMPDIR")).join("NativeMethods.g.cs");
    let rendered = abi_drift::csbindgen_file(
        SOURCES
            .iter()
            .fold(csbindgen::Builder::new(), |b, src| {
                b.input_extern_file(crate_dir().join(src))
            })
            .csharp_dll_name("scull_ffi")
            .csharp_namespace("Scull.Native")
            .csharp_class_name("NativeMethods")
            .csharp_generate_const_filter(|name| name.starts_with("TT_"))
            .csharp_file_header(
                "// Copyright (c) 2026 Ivan Tugay\n\
                 // SPDX-License-Identifier: GPL-3.0-or-later\n\
                 // Generated by csbindgen from crates/scull-ffi/src: `just bindings`. Do not edit.",
            ),
        &out,
    )
    .unwrap();
    drift()
        .check("bindings/csharp/NativeMethods.g.cs", &rendered)
        .unwrap();
}

#[test]
fn a_stale_file_error_contains_a_unified_diff() {
    let header = crate_dir().join("include/scull.h");
    let committed = std::fs::read_to_string(&header).unwrap();
    let err = abi_drift::Drift::new(crate_dir())
        .check("include/scull.h", "not the committed header\n")
        .expect_err("substituted text is stale");
    let shown = err.to_string();
    assert!(shown.contains("--- include/scull.h (committed)"), "{shown}");
    assert!(shown.contains("+++ include/scull.h (generated)"), "{shown}");
    assert!(shown.contains("@@"), "{shown}");
    assert!(shown.contains("+not the committed header"), "{shown}");
    assert_eq!(
        std::fs::read_to_string(&header).unwrap(),
        committed,
        "the stale check must not rewrite the header"
    );
}
